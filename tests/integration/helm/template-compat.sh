#!/bin/sh
# Helm compatibility check for Query.EXTRAS_TEMPLATE against the kind test
# cluster (context kind-tern-kube-dev, namespace tern-test-helm-compat; nothing
# else is touched). Installs the fixture-capture releases with the pinned
# helm, runs the extras template against every revision and decodes each
# output with Parse.extras (tests/integration/helm/compat.luau), so a helm
# bump that changes Go quoting, the release fields the template reads, or
# what --reuse-values stores as chart defaults fails here instead of in
# Explore. stuck-d (a SIGKILLed upgrade) is left out: a pending revision is
# stored like any other and only makes the run slow and timing-dependent.
#
# Evidence (raw outputs, the generated driver input) stays in
# .sandbox/helm-compat/. The namespace is deleted on exit unless KEEP=1.
set -eu

cd "$(dirname "$0")/../../.."

HELM=${HELM:-.tools/bin/helm}
KUBECTL=${KUBECTL:-kubectl}
LUAU=${LUAU:-.tools/bin/luau}
CTX=kind-tern-kube-dev
NS=tern-test-helm-compat
SHOP=tests/fixtures/gitops/helm/chart
STAGING=tests/fixtures/gitops/helm/values-staging.yaml
WEB=tests/fixtures/helm/web
TRICKY=tests/fixtures/helm/values-tricky.yaml
OUT=.sandbox/helm-compat

export KUBECONFIG="$PWD/.sandbox/kubeconfig"
tmp=$(mktemp -d "${TMPDIR:-/tmp}/tk-helm-compat.XXXXXX")
# Never read or write the user's Helm repositories, registry logins or cache.
export HELM_CONFIG_HOME="$tmp/helm/config" HELM_CACHE_HOME="$tmp/helm/cache" HELM_DATA_HOME="$tmp/helm/data"

die() {
	printf 'template-compat: %s\n' "$*" >&2
	exit 1
}

[ -x "$HELM" ] || die "$HELM missing; run 'make bootstrap'"
[ -x "$LUAU" ] || die "$LUAU missing; run 'make bootstrap'"
[ "$("$KUBECTL" config current-context)" = "$CTX" ] || die "refusing: $KUBECONFIG is not the kind test cluster ($CTX)"

h() { "$HELM" --kube-context "$CTX" -n "$NS" "$@"; }
k() { "$KUBECTL" --context "$CTX" "$@"; }

cleanup() {
	if [ "${KEEP:-0}" != 1 ]; then
		k delete namespace "$NS" --ignore-not-found --wait=true --timeout=180s >/dev/null 2>&1 || true
	fi
	rm -rf "$tmp"
}
trap cleanup EXIT
trap 'exit 130' INT TERM

if k get namespace "$NS" >/dev/null 2>&1; then
	k delete namespace "$NS" --wait=true --timeout=180s >/dev/null
fi
k create namespace "$NS" >/dev/null

"$LUAU" scripts/fixtures/helm-template.luau >"$tmp/extras.tpl"
extras=$(cat "$tmp/extras.tpl")

h install shop-a "$SHOP" >/dev/null
h upgrade shop-a "$SHOP" -f "$STAGING" >/dev/null
h upgrade shop-a "$SHOP" --reuse-values --set image.tag=1.27.3-alpine >/dev/null

h install web-b "$WEB" --set auth.password=hunter2-REDACTME --set-string auth.apiToken=tok-REDACTME >/dev/null
"$HELM" package "$WEB" --version 0.2.1 --app-version 2.1 -d "$tmp" >/dev/null
h upgrade web-b "$tmp/web-0.2.1.tgz" --reuse-values --set config.mode=canary --description "canary rollout" >/dev/null
h rollback web-b 1 >/dev/null

# The API server rejects the Service; helm still records a failed revision.
if h install broken-c "$SHOP" --set service.port=99999 >/dev/null 2>&1; then
	die "broken-c installed; expected the API server to reject it"
fi

h install tricky-e "$SHOP" -f "$TRICKY" >/dev/null
h upgrade tricky-e "$SHOP" --reuse-values --set config.mode=reused >/dev/null

rm -rf "$OUT"
mkdir -p "$OUT"

hex() { od -An -v -tx1 | tr -d ' \n'; }

# Revisions created with --reuse-values: their stored chart defaults are the
# previous revision's computed values, which compat.luau checks.
reused() {
	case "$1 $2" in
	"shop-a 3" | "web-b 2" | "tricky-e 2") return 0 ;;
	esac
	return 1
}

count=0
{
	printf -- '--!strict\n-- GENERATED by tests/integration/helm/template-compat.sh\n'
	printf 'return {\n'
	for rel in shop-a web-b broken-c tricky-e; do
		h history "$rel" -o json >"$OUT/history-$rel.json"
		revs=$(tr ',' '\n' <"$OUT/history-$rel.json" | sed -n 's/.*"revision":\([0-9][0-9]*\).*/\1/p')
		[ -n "$revs" ] || die "no revisions for $rel"
		for n in $revs; do
			h get all "$rel" --revision "$n" --template "$extras" >"$OUT/extras-$rel-r$n.txt"
			printf '\t{ release = "%s", namespace = "%s", revision = %s, extras = "%s"' \
				"$rel" "$NS" "$n" "$(hex <"$OUT/extras-$rel-r$n.txt")"
			if reused "$rel" "$n"; then
				h get values "$rel" --revision "$((n - 1))" --all -o json >"$OUT/values-all-$rel-r$((n - 1)).json"
				printf ', previous = "%s"' "$(hex <"$OUT/values-all-$rel-r$((n - 1)).json")"
			fi
			printf ' },\n'
			count=$((count + 1))
		done
	done
	printf '}\n'
} >"$OUT/outputs.luau"

[ "$count" -ge 9 ] || die "expected at least 9 revisions, got $count"
"$LUAU" tests/integration/helm/compat.luau -a outputs
printf 'template-compat: ok (%s, %s revisions)\n' "$("$HELM" version --short)" "$count"
