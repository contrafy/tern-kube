#!/bin/sh
# Copy CLI command, proved against kind: for each drift source Explore offers
# (clean directory, mixed directory, top directory, a quoted path, a
# kustomization, a configured Helm chart) and one two-context matrix, the
# tern-kube-drift command Explore copies (Y / the matrix chip) reports exactly
# what Explore reported, plus the objects another source declares (which the
# CLI, reading only its source, lists as unmanaged).
#   cli_driver.luau  replays Explore headless with real kubectl/git/helm
#                    answers and prints each copied command with the report
#                    the CLI must print;
#   this script      answers the driver's runs, evals each command with
#                    --format json (PATH=bin) and compares normalized
#                    {key, action, +added, -removed} and unmanaged keys.
# The world: tests/integration/manifests/gitops-cli/live.yaml in namespace
# tern-test-gitops-cli (recreated, deleted at exit) and repo/ copied into a
# mktemp git repository (plus a git-ignored YAML and a "we'ird dir"). The
# matrix uses a private copy of the sandbox kubeconfig with a second context
# name for the same cluster (deleted at exit). Nothing else is written: the
# run checks that no ConfigMap or Service resourceVersion (and no Deployment
# generation) changed.
#
#   sh tests/integration/gitops/cli-equivalence.sh
set -u

REPO_ROOT=$(CDPATH='' cd -- "$(dirname -- "$0")/../../.." && pwd -P)
cd "$REPO_ROOT" || exit 2
SANDBOX_KC=$REPO_ROOT/.sandbox/kubeconfig
CTX=kind-tern-kube-dev
ALIAS=tk-cli-alias
NS=tern-test-gitops-cli
LUAU=$REPO_ROOT/.tools/bin/luau
HELM=$REPO_ROOT/.tools/bin/helm
CLI=$REPO_ROOT/bin/tern-kube-drift
WORLD=$REPO_ROOT/tests/integration/manifests/gitops-cli
DRIVER=tests/integration/gitops/cli_driver.luau
T=$REPO_ROOT/tests/integration/gitops/.transcripts

pass=0
failed=0
ok() {
	pass=$((pass + 1))
	printf 'ok   %s\n' "$*"
}
bad() {
	failed=$((failed + 1))
	printf 'FAIL %s\n' "$*"
}
die() {
	printf 'cli-equivalence: %s\n' "$*" >&2
	exit 2
}

[ -f "$SANDBOX_KC" ] || die "missing $SANDBOX_KC: run scripts/cluster.sh create"
[ -x "$HELM" ] || die "missing $HELM: run make bootstrap"
command -v jq >/dev/null 2>&1 || die "jq is required"
command -v xxd >/dev/null 2>&1 || die "xxd is required"
unset KUBECTL_EXTERNAL_DIFF HELM_DRIVER KUBERC

WORK=$(mktemp -d "${TMPDIR:-/tmp}/tk-cli-eq.XXXXXX") || die "mktemp failed"
WORK=$(cd -P "$WORK" && pwd -P)
chmod 700 "$WORK"
REPO=$WORK/repo
KC=$WORK/kubeconfig
DATA=$WORK/data
OUT=$WORK/out

kc() {
	kubectl --kubeconfig "$SANDBOX_KC" --context "$CTX" "$@"
}

cleanup() {
	kc delete namespace "$NS" --ignore-not-found --wait=false >/dev/null 2>&1
	rm -rf "$WORK"
}
trap cleanup EXIT INT TERM

rm -rf "$T"
mkdir -p "$T" "$DATA" "$OUT"

# --- World -------------------------------------------------------------------

kc delete namespace "$NS" --ignore-not-found --wait=true --timeout=180s >/dev/null || die "cannot delete $NS"
kc apply -f "$WORLD/live.yaml" >/dev/null || die "cannot apply live.yaml"

mkdir -p "$REPO"
cp -R "$WORLD/repo/plain" "$WORLD/repo/k8s" "$REPO/"
mkdir -p "$REPO/k8s/we'ird dir"
cp "$WORLD/repo/weird/odd.yaml" "$REPO/k8s/we'ird dir/odd.yaml"
printf 'k8s/app/ignored.yaml\n' >"$REPO/.gitignore"
printf 'apiVersion: v1\nkind: ConfigMap\nmetadata:\n  name: ignored-cm\ndata:\n  git: ignored\n' >"$REPO/k8s/app/ignored.yaml"
git -C "$REPO" init -q -b main || die "git init failed"
git -C "$REPO" -c user.name=tk -c user.email=tk@example.invalid add -A
git -C "$REPO" -c user.name=tk -c user.email=tk@example.invalid commit -q -m world || die "git commit failed"

(umask 077 && cp "$SANDBOX_KC" "$KC")
kubectl --kubeconfig "$KC" config set-context "$ALIAS" --cluster="$CTX" --user="$CTX" >/dev/null || die "cannot add $ALIAS"

snapshot() {
	{
		kc -n "$NS" get configmaps,services -o \
			jsonpath='{range .items[*]}{.kind}/{.metadata.name} {.metadata.resourceVersion}{"\n"}{end}'
		kc -n "$NS" get deployments -o \
			jsonpath='{range .items[*]}{.kind}/{.metadata.name} {.metadata.generation}{"\n"}{end}'
	} | sort
}
snapshot >"$OUT/before.txt" || die "cannot snapshot $NS"

hexof() {
	od -An -v -tx1 | tr -d ' \n'
}

# What gitops_host.luau indexes: git ls-files -co --exclude-standard.
{
	printf -- '--!strict\n-- Generated by cli-equivalence.sh: indexed files, hex contents.\nreturn {\n'
	git -C "$REPO" ls-files -co --exclude-standard -z -- '*.yaml' '*.yml' '*Kustomization' |
		tr '\0' '\n' | while IFS= read -r rel; do
		printf '\t["%s"] = "%s",\n' "$REPO/$rel" "$(hexof <"$REPO/$rel")"
	done
	printf '}\n'
} >"$T/files.luau"

# --- Driver --------------------------------------------------------------------

# tk_need KEY TIMEOUT_MS ARGV...: run one read-only call the driver asked for.
tk_need() {
	key_=$1
	ms_=$2
	shift 2
	case $1 in
	kubectl)
		for w_ in "$@"; do
			case $w_ in
			apply | create | delete | patch | edit | replace | scale | rollout | label | annotate | drain | cordon | uncordon | taint | set | exec | run | debug | cp | port-forward | attach | proxy)
				die "driver asked for a non-read-only call: $*"
				;;
			esac
		done
		case " $* " in
		*" kustomize "* | *" --kubeconfig $KC "*) ;;
		*) die "driver asked for a call without --kubeconfig $KC: $*" ;;
		esac
		;;
	git)
		[ "$2" = -C ] && [ "$3" = "$REPO" ] || die "git outside the world repo: $*"
		case " $* " in
		*" remote "* | *" status "* | *" rev-parse "* | *" ls-files "*) ;;
		*) die "git call not allowed: $*" ;;
		esac
		;;
	"$HELM")
		case " $* " in *" template "* | *" list "*) ;; *) die "helm call not allowed: $*" ;; esac
		;;
	*) die "driver asked to run '$1'" ;;
	esac
	secs_=$(((ms_ + 999) / 1000))
	[ "$secs_" -gt 0 ] || secs_=60
	KUBECONFIG=$KC "$@" >"$T/stdout" 2>"$T/stderr" &
	pid_=$!
	(sleep "$secs_" && kill "$pid_" 2>/dev/null) &
	dog_=$!
	wait "$pid_"
	rc_=$?
	kill "$dog_" 2>/dev/null
	wait "$dog_" 2>/dev/null
	printf '%s rc=%s\n' "$*" "$rc_" >>"$OUT/runs.log"
	printf '\t["%s"] = { status = %d, out = "%s", err = "%s", timedOut = false },\n' \
		"$key_" "$rc_" "$(hexof <"$T/stdout")" "$(hexof <"$T/stderr")" >>"$T/body"
}

# tk_write PATH HEX: a temporary manifest Explore wrote; kubectl diff reads it.
tk_write() {
	case $1 in "$DATA"/*) ;; *) die "write outside the data dir: $1" ;; esac
	mkdir -p "$(dirname "$1")"
	(umask 077 && printf '%s' "$2" | xxd -r -p >"$1")
}

tk_ok() {
	ok "explore $1"
}

tk_fail() {
	bad "explore $1: $2"
}

# Normalized CLI JSON: one line per diffed object, unmanaged object (v1) or
# matrix row (v2), keys as group/Kind/namespace/name like the plugin.
NORMALIZE='def k: "\(.group // "")/\(.kind)/\(.namespace // "")/\(.name)";
if .version == 2 then
	(.matrix[] | "cell \(k) \([.cells[].state] | join(" "))")
else
	(.resources[] | "resource \(k) \(.action) +\(.added) -\(.removed)"),
	((.unmanaged // [])[] | "unmanaged \(k)")
end'

# tk_cli NAME COMMAND EXPECTED: run the copied command, compare its report.
tk_cli() {
	name_=$1
	printf '%s\n' "$2" >"$OUT/$name_.cmd"
	printf '%s\n' "$3" >"$OUT/$name_.explore"
	(
		PATH=$REPO_ROOT/bin:$REPO_ROOT/.tools/bin:$PATH
		export PATH
		eval "$2 --format json"
	) >"$OUT/$name_.json" 2>"$OUT/$name_.err"
	rc_=$?
	if [ "$rc_" -gt 1 ]; then
		bad "cli $name_: exit $rc_: $(head -c 600 "$OUT/$name_.err")"
		return
	fi
	if ! jq -r "$NORMALIZE" "$OUT/$name_.json" | LC_ALL=C sort >"$OUT/$name_.cli"; then
		bad "cli $name_: unreadable JSON"
		return
	fi
	LC_ALL=C sort "$OUT/$name_.explore" -o "$OUT/$name_.explore"
	if cmp -s "$OUT/$name_.cli" "$OUT/$name_.explore"; then
		ok "cli $name_ = explore ($(wc -l <"$OUT/$name_.cli" | tr -d ' ') lines): $2"
	else
		bad "cli $name_ differs from explore: $2"
		diff "$OUT/$name_.explore" "$OUT/$name_.cli" | sed 's/^/    /' | head -n 30
	fi
}

: >"$T/body"
round=0
while :; do
	{
		printf -- '--!strict\n-- Generated by cli-equivalence.sh: answers keyed by hex(argv joined by NUL).\nreturn {\n'
		cat "$T/body"
		printf '}\n'
	} >"$T/answers.luau"
	if ! lines=$("$LUAU" "$DRIVER" -a "$REPO" "$KC" "$DATA" "$HELM" "$ALIAS" 2>"$T/driver.err"); then
		bad "driver: $(cat "$T/driver.err")"
		break
	fi
	case $lines in
	*tk_need*)
		round=$((round + 1))
		[ "$round" -le 40 ] || {
			bad "driver still needs answers after 40 rounds"
			break
		}
		eval "$lines"
		;;
	*)
		eval "$lines"
		break
		;;
	esac
done

# --- Read-only -------------------------------------------------------------------

snapshot >"$OUT/after.txt" || die "cannot snapshot $NS"
if cmp -s "$OUT/before.txt" "$OUT/after.txt"; then
	ok "read-only: $(wc -l <"$OUT/before.txt" | tr -d ' ') objects unchanged"
else
	bad "read-only: objects changed: $(diff "$OUT/before.txt" "$OUT/after.txt" | head -n 10)"
fi

printf '%d passed, %d failed\n' "$pass" "$failed"
[ "$failed" -eq 0 ]
